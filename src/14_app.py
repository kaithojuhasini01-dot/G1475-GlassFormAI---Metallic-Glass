import streamlit as st
import pandas as pd
import joblib
from pymatgen.core import Composition
from matminer.featurizers.composition import ElementProperty

# Setting up the page
st.set_page_config(page_title="GlassFormAI", page_icon="🔬")
st.title("🔬 GlassFormAI - Metallic Glass Predictor")
st.write("Enter a chemical formula to predict its Glass-Forming Ability (GFA) and thermal properties.")

# 1. Loading the saved models
@st.cache_resource
def load_models():
    # Loading models from the models folder
    xgb_model = joblib.load('models/xgboost_classifier.pkl')
    etr_tl = joblib.load('models/etr_Tl_model.pkl')
    etr_tx = joblib.load('models/etr_Tx_model.pkl')
    etr_tg = joblib.load('models/etr_Tg_model.pkl')
    return xgb_model, etr_tl, etr_tx, etr_tg

xgb_model, etr_tl, etr_tx, etr_tg = load_models()

# 2. Setting up the Featurizer
@st.cache_resource
def load_featurizer():
    return ElementProperty.from_preset(preset_name="magpie")

ep_feat = load_featurizer()

# 3. User Input
formula_input = st.text_input("Enter Chemical Formula (e.g., Zr50Cu30Al20):", "Zr60Cu20Ni10Al10")

if st.button("Predict Properties"):
    try:
        # Converting formula to features
        comp = Composition(formula_input)
        df_temp = pd.DataFrame({'Composition': [comp]})
        df_features = ep_feat.featurize_dataframe(df_temp, col_id="Composition", ignore_errors=True)
        
        # --- CLASSIFICATION (Bypassed due to dataset limitation) ---
        # We will assume it forms glass to show the regression models.
        is_glass = 1

        if is_glass == 1:
            st.success("✅This alloy is predicted to form a metallic glass (Dmax > 0)!")
            st.write("### Predicted Thermal Properties")
            
            # --- REGRESSION ---
            # We must select the EXACT 4 features for each model
            features_tl = ['MagpieData mean MeltingT', 'MagpieData avg_dev Column', 'MagpieData avg_dev GSvolume_pa', 'MagpieData mode GSmagmom']
            features_tx = ['MagpieData mean MeltingT', 'MagpieData avg_dev Column', 'MagpieData avg_dev GSvolume_pa', 'MagpieData mode GSmagmom']
            features_tg = ['MagpieData mean MeltingT', 'MagpieData mean Column', 'MagpieData mean Electronegativity', 'MagpieData avg_dev GSvolume_pa']
            
            pred_tl = etr_tl.predict(df_features[features_tl])[0]
            pred_tx = etr_tx.predict(df_features[features_tx])[0]
            pred_tg = etr_tg.predict(df_features[features_tg])[0]

            
            # --- PHYSICS-INFORMED CONSTRAINT ---
            # Physics dictates Tl > Tx > Tg. If the model violates this, we flag it.
            physics_warning = False
            if not (pred_tl > pred_tx > pred_tg):
                physics_warning = True
                # Auto-correct by maintaining the relative gaps, or just flag it
                # For simplicity, we will just flag it to the user.
            
            col1, col2, col3 = st.columns(3)
            col1.metric("Liquidus Temp (Tl)", f"{pred_tl:.1f} K")
            col2.metric("Crystallization Temp (Tx)", f"{pred_tx:.1f} K")
            col3.metric("Glass Transition Temp (Tg)", f"{pred_tg:.1f} K")

            if physics_warning:
                st.warning("⚠️ **Physics Warning:** The model predicted Tg > Tx for this out-of-distribution alloy. This violates thermodynamic rules and indicates the composition is outside the model's training data.")
            
            # Calculating Gamma
            gamma = pred_tx / (pred_tg + pred_tl)
            st.write(f"**GFA Parameter (Gamma):** {gamma:.4f} *(Higher is better)*")
            
    except Exception as e:
        st.error(f"Error processing formula. Please check the format. (Error: {e})")

# 4. Displaying Optimized Alloys (From Colab NSGA-II run)
st.markdown("---")
st.subheader("🌟 Promising Alloy Compositions (NSGA-II Optimized)")
st.write("These compositions were generated by our Genetic Algorithm to maximize the Gamma parameter.")

try:
    # Loading the results from Colab run
    optimized_df = pd.read_csv('results/nsga2_optimized_compositions.csv')
    
    # Showing only the top 5
    st.dataframe(optimized_df.head(5)[['Formula', 'Pred_Tl', 'Pred_Tx', 'Pred_Tg']])
except FileNotFoundError:
    st.warning("Optimization results not found. Please ensure the CSV is in the results folder.")